#!/usr/bin/env python3

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd


def main() -> None:
    ap = argparse.ArgumentParser(description="Split CPTAC clini/slide inputs by cancer type.")
    ap.add_argument("--labels", required=True, help="CPTAC SBS xlsx with PATIENT, Cancer_Type, SBS*")
    ap.add_argument("--slide-csv", required=True, help="Global slide csv generated by prepare_cptac_reg_inputs.py")
    ap.add_argument("--out-dir", required=True, help="Output root directory")
    ap.add_argument("--project-prefix", default="CPTAC", help="Project prefix")
    args = ap.parse_args()

    labels = pd.read_excel(args.labels, dtype={"PATIENT": str, "Cancer_Type": str})
    slides = pd.read_csv(args.slide_csv, dtype={"PATIENT": str})
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    sbs_cols = [c for c in labels.columns if str(c).startswith("SBS")]
    if "Cancer_Type" not in labels.columns:
        raise KeyError("Cancer_Type column not found in labels table.")

    made = 0
    for cancer_type, clini_df in labels.dropna(subset=["Cancer_Type"]).groupby("Cancer_Type", sort=True):
        clini_df = clini_df[["PATIENT", *sbs_cols]].drop_duplicates(subset=["PATIENT"]).reset_index(drop=True)
        keep_patients = set(clini_df["PATIENT"].astype(str))
        slide_df = slides[slides["PATIENT"].astype(str).isin(keep_patients)].reset_index(drop=True)
        if clini_df.empty or slide_df.empty:
            continue

        cancer_slug = str(cancer_type)
        cancer_dir = out_dir / cancer_slug
        cancer_dir.mkdir(parents=True, exist_ok=True)

        clini_path = cancer_dir / f"{args.project_prefix}_{cancer_slug}.xlsx"
        slide_path = cancer_dir / f"{args.project_prefix}_{cancer_slug}_csv.csv"
        clini_df.to_excel(clini_path, index=False)
        slide_df.to_csv(slide_path, index=False)
        print(f"[OK] {cancer_slug}: patients={clini_df['PATIENT'].nunique()} slides={len(slide_df)}")
        made += 1

    print(f"[DONE] cohorts written: {made}")


if __name__ == "__main__":
    main()
